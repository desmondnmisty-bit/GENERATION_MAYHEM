import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage(); const errs = [];
page.on('pageerror', (e) => errs.push(String(e))); page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()); });
await page.setViewport({ width: 960, height: 540 });
await page.goto('http://localhost:4181/', { waitUntil: 'load' });
await page.waitForFunction(() => window.__gm && window.__gm.ready, { timeout: 180000 });
await page.keyboard.press('Space'); await new Promise(r => setTimeout(r, 500));
await page.click('#btn-play'); await new Promise(r => setTimeout(r, 2000));
const st = () => page.evaluate(() => { const g = window.__gm; return JSON.stringify({ st: g.state, lvl: g.level, wave: g.wave, chaos: Math.round(g.chaos), rage: +g.rage.toFixed(1), why: g.frenzyReason, reason: document.getElementById('frenzy-reason').textContent, coms: document.getElementById('coms').textContent, en: g.enemyCount }); });
console.log('L1', await st());
await page.evaluate(() => { const g = window.__gm; g.setInvuln(999); g.setChaos(55); g.spawn('v', 2, 0); g.spawn('v', -2, 3); g.damageKailee(20); });
await new Promise(r => setTimeout(r, 1500)); console.log('threat', await st());
await page.screenshot({ path: 'shots/frenzy_rage.png' });
await page.evaluate(() => window.__gm.downPayton()); await new Promise(r => setTimeout(r, 3000)); console.log('paytonDown', await st());
await new Promise(r => setTimeout(r, 9000)); console.log('paytonUp', await st());
await page.evaluate(() => window.__gm.winDock()); await new Promise(r => setTimeout(r, 4000));
console.log('cutscene', await st(), await page.evaluate(() => document.querySelector('#cutscene .cap')?.textContent));
await page.screenshot({ path: 'shots/cutscene.png' });
await page.mouse.click(400, 300); await new Promise(r => setTimeout(r, 4000));
console.log('L2', await st());
await page.keyboard.down('KeyW'); await new Promise(r => setTimeout(r, 4000)); await page.keyboard.up('KeyW');
console.log('L2b', await st());
await page.screenshot({ path: 'shots/l2_hyperdrive.png' });
console.log('ERR', errs.slice(0, 10));
await browser.close();
