import puppeteer from 'puppeteer-core';
const OUT=process.argv[2], KAI=process.argv[3]==='k';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage(); await p.setViewport({ width: 1280, height: 720 });
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.evaluateOnNewDocument(() => { window.__gmNoAutoQuality = true; });
await p.goto('http://localhost:4181/', { waitUntil: 'load' });
await p.waitForFunction(() => window.__gm && window.__gm.ready, { timeout: 120000 });
await p.click('#btn-play'); await new Promise(r => setTimeout(r, 2000));
await p.evaluate((KAI)=>{ const g=window.__gm.game; g.introT=1e9; const V=g.vixen.pos.constructor; const c=g.camera;
  const a=KAI?g.kailee.pos:g.vixen.pos;
  const pts=KAI?[[-1.0,1.2,'v'],[1.3,1.6,'v']]:[[-2.5,9,'v'],[0,10,'e'],[2.5,9,'v']];
  for (const [x,z,t] of pts) g.spawnEnemy(t,new V(a.x+x,0,a.z+z));
  g.update=((u)=>function(dt){u.call(this,dt); const q=a; if(KAI){c.position.set(q.x+2.4,1.7,q.z-2.2);c.lookAt(q.x,0.9,q.z+0.8);} else {c.position.set(q.x,2.4,q.z-2.5);c.lookAt(q.x,1.0,q.z+9);} })(g.update);
},KAI);
await new Promise(r => setTimeout(r, KAI?3500:4500));
if (KAI) await p.keyboard.press('j');
await new Promise(r => setTimeout(r, 350));
await p.screenshot({ path: 'shots/'+OUT+'.png' }); console.log('errs',errs); await b.close();
